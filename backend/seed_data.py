def ev(year, title, desc, status=D):
    return {"year": year, "title": title, "desc": desc, "status": status}


def st(name, desc):
    return {"name": name, "desc": desc}


def F(slug, name, alt, district, region, ftype, lat, lng, period, assoc, difficulty, access, popularity, condition,
      summary, history, shivaji, events, strategic, architecture, structures, facts, legends, conservation, travel,
      refs, elevation=None, imgs=None, featured=False):
    pool = imgs or (SEA_IMGS if ftype in ("Sea Fort", "Island Fort") else LAND_IMGS if ftype == "Land Fort" else HILL_IMGS)
    i = sum(ord(c) for c in slug) % len(pool)
    ordered = pool[i:] + pool[:i]
    rep = imgs is None
    gallery = [{"url": U.format(p), "credit": "Unsplash contributor", "license": "Unsplash License",
                "source": "https://unsplash.com", "representative": rep} for p in ordered[:4]]
    art_key = "sea" if ftype in ("Sea Fort", "Island Fort") else "hill"
    gallery.append({"url": ART[art_key], "credit": "Forts of Maharashtra (AI-generated illustration)",
                    "license": "Illustration — not a historical record", "source": "", "representative": True})
    return {
        "slug": slug, "name": name, "alt_names": alt, "district": district, "region": region, "type": ftype,
        "lat": lat, "lng": lng, "elevation_m": elevation, "period": period, "associations": assoc,
        "difficulty": difficulty, "accessibility": access, "popularity": popularity, "condition": condition,
        "summary": summary, "history": history, "shivaji_association": shivaji, "events": events,
        "strategic_importance": strategic, "architecture": architecture, "structures": structures,
        "facts": facts, "legends": legends, "conservation": conservation, "travel": travel, "references": refs,
        "hero_image": gallery[0]["url"], "gallery": gallery, "featured": featured, "published": True,
        "verification": "sourced", "views": 0,
    }


